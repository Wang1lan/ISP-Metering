function [value, debug] = computeRegionalMean(numerator, denominator, cfg, luts)
%COMPUTEREGIONALMEAN 计算可靠度加权平均，保留 double 小数及 0~255 限幅。
% 调用者须先判断区域权重和严格大于 cfg.sumWMin。
% LUT 分支只访问已加载 float 表；不生成表、不读文件、不计算参考除法。

    validateattributes(numerator, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'nonnegative'}, mfilename, 'numerator');
    validateattributes(denominator, {'numeric'}, ...
        {'real', 'finite', 'scalar', 'positive'}, mfilename, 'denominator');
    validateattributes(cfg, {'struct'}, {'scalar'}, mfilename, 'cfg');
    method = 'division';
    if isfield(cfg, 'regionMeanMethod')
        method = cfg.regionMeanMethod;
    end
    assert((ischar(method) && isrow(method)) || ...
        (isstring(method) && isscalar(method) && ~ismissing(method)), ...
        'computeRegionalMean:InvalidMethod', 'regionMeanMethod 必须是有效文本标量。');
    method = char(method);
    numerator = double(numerator);
    denominator = double(denominator);
    debug = struct('method', method, 'numerator', numerator, ...
        'denominator', denominator, 'normalizedDenominator', NaN, ...
        'exponent', NaN, 'address', NaN, 'reciprocal', NaN, 'rawMean', NaN);
    switch method
        case 'division'
            debug.rawMean = numerator / denominator;
        case 'reciprocal_lut'
            assert(isstruct(luts) && isscalar(luts) && ...
                all(isfield(luts, {'reciprocal', 'meta'})) && ...
                isstruct(luts.meta) && isscalar(luts.meta) && ...
                isfield(luts.meta, 'reciprocal') && ...
                isstruct(luts.meta.reciprocal) && isscalar(luts.meta.reciprocal), ...
                'computeRegionalMean:InvalidLUT', '请先初始化倒数浮点表及元数据。');
            meta = luts.meta.reciprocal;
            assert(all(isfield(meta, {'addrBits', 'length', 'normalizedMin', ...
                'normalizedMax', 'sampleRule', 'addressBase', 'addressFormula'})) && ...
                isnumeric(meta.addrBits) && isreal(meta.addrBits) && ...
                isscalar(meta.addrBits) && isfinite(meta.addrBits) && ...
                meta.addrBits >= 1 && meta.addrBits == floor(meta.addrBits) && ...
                isequal(meta.length, 2 ^ double(meta.addrBits)) && ...
                isequal(meta.normalizedMin, 1) && isequal(meta.normalizedMax, 2) && ...
                isequal(meta.addressBase, 0) && strcmp(meta.sampleRule, 'midpoint') && ...
                strcmp(meta.addressFormula, 'floor((m-1)*2^addrBits)') && ...
                isa(luts.reciprocal, 'double') && isreal(luts.reciprocal) && ...
                isequal(size(luts.reciprocal), [meta.length, 1]), ...
                'computeRegionalMean:InvalidLUT', '倒数表结构或地址约定不正确。');
            [debug.rawMean, divisionDebug] = divideByReciprocalLUT( ...
                numerator, denominator, luts);
            debug.normalizedDenominator = divisionDebug.normalizedDenominator;
            debug.exponent = divisionDebug.exponent;
            debug.address = divisionDebug.address;
            debug.reciprocal = divisionDebug.reciprocal;
            assert(isfinite(debug.reciprocal) && debug.reciprocal > 0.5 && ...
                debug.reciprocal < 1, 'computeRegionalMean:InvalidCoefficient', ...
                '倒数系数必须有限且在 (0.5,1)。');
        otherwise
            error('computeRegionalMean:InvalidMethod', ...
                '未知 regionMeanMethod：%s。', method);
    end
    value = min(255, max(0, debug.rawMean));
end
